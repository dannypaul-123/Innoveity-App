class Payslip {
  final String id, userId, batchId, month, status;
  final int year;
  final num basicSalary,
      hra,
      da,
      grossSalary,
      netSalary,
      workingDays,
      presentDays,
      paidLeaveDays,
      overtimeHours,
      overtimePay;
  final dynamic allowancesJson, deductionsJson;
  final String? pdfPath;
  const Payslip({
    required this.id,
    required this.userId,
    required this.batchId,
    required this.month,
    required this.year,
    required this.basicSalary,
    required this.hra,
    required this.da,
    required this.allowancesJson,
    required this.deductionsJson,
    required this.grossSalary,
    required this.netSalary,
    required this.workingDays,
    required this.presentDays,
    required this.paidLeaveDays,
    required this.overtimeHours,
    required this.overtimePay,
    required this.status,
    this.pdfPath,
  });
  factory Payslip.fromJson(Map<String, dynamic> j) => Payslip(
    id: '${j['id']}',
    userId: '${j['userId']}',
    batchId: '${j['batchId']}',
    month: '${j['month']}',
    year: (j['year'] as num?)?.toInt() ?? 0,
    basicSalary: j['basicSalary'] as num? ?? 0,
    hra: j['hra'] as num? ?? 0,
    da: j['da'] as num? ?? 0,
    allowancesJson: j['allowancesJson'],
    deductionsJson: j['deductionsJson'],
    grossSalary: j['grossSalary'] as num? ?? 0,
    netSalary: j['netSalary'] as num? ?? 0,
    workingDays: j['workingDays'] as num? ?? 0,
    presentDays: j['presentDays'] as num? ?? 0,
    paidLeaveDays: j['paidLeaveDays'] as num? ?? 0,
    overtimeHours: j['overtimeHours'] as num? ?? 0,
    overtimePay: j['overtimePay'] as num? ?? 0,
    status: '${j['status'] ?? ''}',
    pdfPath: j['pdfPath']?.toString(),
  );
  Map<String, dynamic> toJson() => {
    'id': id,
    'userId': userId,
    'batchId': batchId,
    'month': month,
    'year': year,
    'basicSalary': basicSalary,
    'hra': hra,
    'da': da,
    'allowancesJson': allowancesJson,
    'deductionsJson': deductionsJson,
    'grossSalary': grossSalary,
    'netSalary': netSalary,
    'workingDays': workingDays,
    'presentDays': presentDays,
    'paidLeaveDays': paidLeaveDays,
    'overtimeHours': overtimeHours,
    'overtimePay': overtimePay,
    'status': status,
    'pdfPath': pdfPath,
  };
}
