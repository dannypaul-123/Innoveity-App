class User {
  final String id, employeeId, name, email, role;
  final String? phone,
      dob,
      department,
      joiningDate,
      status,
      profilePic,
      designation,
      organizationId,
      positionId,
      branchId,
      shiftId,
      employmentType;
  final num? casualLeaveQuota, sickLeaveQuota, emergencyLeaveQuota;
  const User({
    required this.id,
    required this.employeeId,
    required this.name,
    required this.email,
    required this.role,
    this.phone,
    this.dob,
    this.department,
    this.joiningDate,
    this.status,
    this.profilePic,
    this.designation,
    this.casualLeaveQuota,
    this.sickLeaveQuota,
    this.emergencyLeaveQuota,
    this.organizationId,
    this.positionId,
    this.branchId,
    this.shiftId,
    this.employmentType,
  });
  factory User.fromJson(Map<String, dynamic> j) => User(
    id: '${j['id']}',
    employeeId: '${j['employeeId'] ?? ''}',
    name: '${j['name'] ?? ''}',
    email: '${j['email'] ?? ''}',
    role: '${j['role'] ?? 'EMPLOYEE'}',
    phone: j['phone']?.toString(),
    dob: j['dob']?.toString(),
    department: j['department']?.toString(),
    joiningDate: j['joiningDate']?.toString(),
    status: j['status']?.toString(),
    profilePic: j['profilePic']?.toString(),
    designation: j['designation']?.toString(),
    casualLeaveQuota: j['casualLeaveQuota'] as num?,
    sickLeaveQuota: j['sickLeaveQuota'] as num?,
    emergencyLeaveQuota: j['emergencyLeaveQuota'] as num?,
    organizationId: j['organizationId']?.toString(),
    positionId: j['positionId']?.toString(),
    branchId: j['branchId']?.toString(),
    shiftId: j['shiftId']?.toString(),
    employmentType: j['employmentType']?.toString(),
  );
  Map<String, dynamic> toJson() => {
    'id': id,
    'employeeId': employeeId,
    'name': name,
    'email': email,
    'role': role,
    'phone': phone,
    'dob': dob,
    'department': department,
    'joiningDate': joiningDate,
    'status': status,
    'profilePic': profilePic,
    'designation': designation,
    'casualLeaveQuota': casualLeaveQuota,
    'sickLeaveQuota': sickLeaveQuota,
    'emergencyLeaveQuota': emergencyLeaveQuota,
    'organizationId': organizationId,
    'positionId': positionId,
    'branchId': branchId,
    'shiftId': shiftId,
    'employmentType': employmentType,
  };
}
